// Local generated media in built Storybook. Verifies playback/fallback behavior, not a live generation.
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { launch, serve } from "./browser.ts";
const root = join(import.meta.dir, "..");
const out = join(root, "artifacts/material-lab");
await mkdir(out, { recursive: true });
const server = serve(join(root, "storybook-static"));
const browser = await launch();
const checks: string[] = [];
try {
  const page = await browser.newPage({ viewport: { width: 900, height: 700 }, reducedMotion: "no-preference" });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/*", (route) => new URL(route.request().url()).origin === server.url ? route.continue() : route.abort());
  await page.goto(`${server.url}/iframe.html?id=motion-ambientmaterial--entrance&viewMode=story`);
  await page.waitForFunction(() => {
    const video = document.querySelector("video");
    return video && video.currentTime > 0.15 && !video.paused && video.videoWidth > 0;
  });
  assert.equal(await page.locator("video").evaluate((node: HTMLVideoElement) => node.muted && !node.loop), true);
  await page.getByRole("button", { name: "Pause background light" }).click();
  assert.equal(await page.locator("video").evaluate((node: HTMLVideoElement) => node.paused), true);
  const paused = await page.locator("video").evaluate((node: HTMLVideoElement) => node.currentTime);
  await page.waitForTimeout(250);
  assert.equal(await page.locator("video").evaluate((node: HTMLVideoElement) => node.currentTime), paused);
  await page.getByRole("button", { name: "Play background light" }).click();
  await page.waitForFunction(() => !document.querySelector("video")?.paused);
  await page.locator("video").evaluate((node: HTMLVideoElement) => { node.currentTime = Math.max(0, node.duration - 0.2); });
  await page.waitForFunction(() => document.querySelector("video")?.ended);
  assert.equal(await page.locator(".ambient-material").getAttribute("data-playing"), "false");
  checks.push("actual decoded frames, mute, pause, resume and single-play termination");
  await page.getByRole("button", { name: "Play background light" }).click();
  await page.waitForFunction(() => !document.querySelector("video")?.paused);
  await page.evaluate(() => {
    Object.defineProperty(document, "hidden", { configurable: true, value: true });
    document.dispatchEvent(new Event("visibilitychange"));
  });
  await page.waitForFunction(() => document.querySelector("video")?.paused);
  checks.push("hidden tab stops playback without automatic restart");
  await page.reload();
  await page.waitForFunction(() => Boolean(document.querySelector("video")?.videoWidth));
  await page.locator(".ambient-material").evaluate((node) => { node.style.top = "1800px"; node.style.bottom = "auto"; node.style.height = "400px"; });
  await page.waitForFunction(() => document.querySelector("video")?.paused);
  checks.push("offscreen layer stops playback");
  await page.emulateMedia({ reducedMotion: "reduce" });
  let movieRequests = 0;
  page.on("request", (request) => { if (/\.(mp4|webm)(?:\?|$)/.test(request.url())) movieRequests++; });
  await page.reload();
  await page.locator(".ambient-material").waitFor();
  assert.equal(await page.locator("video").count(), 0);
  assert.equal(await page.getByRole("button", { name: "Play background light" }).isEnabled(), false);
  assert.equal(movieRequests, 0);
  checks.push("reduced motion leaves the poster and never requests a video");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.route("**/kling-living-glass.webm", (route) => route.abort());
  await page.route("**/kling-living-glass.mp4", (route) => route.abort());
  await page.reload();
  await page.locator(".ambient-material").waitFor();
  await page.waitForTimeout(500);
  assert.equal(await page.locator(".ambient-material").getAttribute("data-playing"), "false");
  assert.ok((await page.locator(".ambient-material").evaluate((node) => getComputedStyle(node).backgroundImage)).includes(".webp"));
  checks.push("missing video keeps the still artwork");
  const saving = await browser.newPage({ viewport: { width: 390, height: 700 }, reducedMotion: "no-preference" });
  await saving.addInitScript(() => Object.defineProperty(navigator, "connection", { value: { saveData: true } }));
  await saving.goto(`${server.url}/iframe.html?id=motion-ambientmaterial--entrance&viewMode=story`);
  await saving.getByRole("button", { name: "Play background light" }).waitFor();
  assert.equal(await saving.locator("video").count(), 0);
  await saving.getByRole("button", { name: "Play background light" }).click();
  await saving.waitForFunction(() => Boolean(document.querySelector("video")?.videoWidth));
  checks.push("data saving avoids automatic download but permits explicit playback");
  assert.deepEqual(errors, []);
  await writeFile(join(out, "ambient-checks.json"), JSON.stringify({ checks, boundary: "Local media and browser only." }, null, 2));
  console.log(`PASS ${checks.length} ambient motion lifecycle groups`);
} finally { await browser.close(); server.stop(); }
